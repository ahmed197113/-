const W = 10466; // عرض المحتوى (A4 بهوامش 720)

// ------------------------------------------------------------------ أدوات أساسية
const run = (t, o = {}) => new TextRun({ text: t, font: FONT, rightToLeft: true, size: o.size || 20, bold: o.bold, color: o.color, italics: o.italic });
const para = (t, o = {}) => new Paragraph({
  bidirectional: true,
  alignment: o.align || AlignmentType.RIGHT,
  spacing: { before: o.before || 0, after: o.after === undefined ? 60 : o.after },
  children: Array.isArray(t) ? t : [run(t, o)],
  border: o.border,
});
const b = (c = LINE, sz = 4) => ({ style: BorderStyle.SINGLE, size: sz, color: c });
const BORD = { top: b(), bottom: b(), left: b(), right: b() };
const NOB = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
const NOBORD = { top: NOB, bottom: NOB, left: NOB, right: NOB };

function cell(content, width, o = {}) {
  const kids = (Array.isArray(content) ? content : [content]).map((c) =>
    typeof c === "string" ? para(c, { bold: o.bold, color: o.color, size: o.size, align: o.align, after: 0 }) : c);
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    columnSpan: o.span,
    borders: o.noBorder ? NOBORD : BORD,
    shading: o.fill ? { type: ShadingType.CLEAR, color: "auto", fill: o.fill } : undefined,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 50, bottom: 50, left: 90, right: 90 },
    children: kids,
  });
}
function table(widths, rows, o = {}) {
  return new Table({
    width: { size: widths.reduce((a, x) => a + x, 0), type: WidthType.DXA },
    columnWidths: widths,
    visuallyRightToLeft: true,
    layout: TableLayoutType.FIXED,
    rows: rows.map((r) => new TableRow({
      height: o.h ? { value: o.h, rule: HeightRule.ATLEAST } : undefined,
      tableHeader: r.header, cantSplit: true, children: r.cells || r,
    })),
  });
}
const spacer = (after = 100) => new Paragraph({ spacing: { after }, children: [] });

