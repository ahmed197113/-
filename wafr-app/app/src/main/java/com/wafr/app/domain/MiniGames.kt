/** Compound growth for the time machine. */
object TimeMachine {
    /** Yearly balances (index 0 = after year 1) for a monthly deposit compounded monthly. */
    fun series(monthly: Double, years: Int, annualRate: Double): List<Pair<Double, Double>> {
        val r = annualRate / 12
        var balance = 0.0
        var deposited = 0.0
        val out = mutableListOf<Pair<Double, Double>>()
        for (m in 1..years * 12) {
            balance = balance * (1 + r) + monthly
            deposited += monthly
            if (m % 12 == 0) out += deposited to balance
        }
        return out
    }

    fun yearsTo(target: Double, monthly: Double, annualRate: Double): Int? {
        if (monthly <= 0) return null
        val r = annualRate / 12
        var balance = 0.0
        for (m in 1..12 * 80) {
            balance = balance * (1 + r) + monthly
            if (balance >= target) return (m + 11) / 12
        }
        return null
    }

    fun doublingYears(annualRate: Double): Double = if (annualRate > 0) 72 / (annualRate * 100) else Double.NaN

    @Suppress("unused")
    fun lump(amount: Double, years: Int, rate: Double) = amount * (1 + rate).pow(years)
}
